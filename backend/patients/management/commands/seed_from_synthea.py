"""
Seed the MedInsight database with realistic synthetic data for demos.

Source of truth: MITRE Synthea output. The exact reproducible command that
produces the CSV consumed here is documented in backend/seed_data/synthea/README.md
(and in the file header of backend/seed_data/synthea/generate_patients.py).

What this command creates
-------------------------
* Patient records from Synthea's `patients.csv` demographics.
* A handful of Family groupings — some households are linked into real Family
  records (so the patient "Family" tab shows a member list), while other
  household clusters are intentionally left ungrouped so Step 4's "possible
  family" banner has real matches to show during a demo.
* Appointment records spread across past and upcoming dates with a realistic
  mix of statuses (scheduled / completed / cancelled / no_show).
* A few sample Documents attached to some patients (placeholder PDFs) so the
  document list and "Run OCR" button both have something to click.
* Dev login accounts (one admin, one doctor, one receptionist) created /
  verified, with documented credentials (see the README).

Idempotency / safety
--------------------
* Users are created only if they don't already exist (existing dev logins are
  reused, never clobbered).
* Patient/Family/Appointment/Document data is only written when the database is
  empty of patient data, OR when `--flush` is passed to wipe those tables first.
  This keeps the command safe to re-run during a demo without deleting the data
  you already created manually.

Mapping decisions (Synthea -> MedInsight) — documented for reviewers
--------------------------------------------------------------------
* full_name        = FIRST + " " + LAST
* date_of_birth    = BIRTHDATE (YYYYMMDD -> YYYY-MM-DD)
* gender           = Synthea GENDER ('M'/'F' / can be empty) -> model choices
                    male/female/other.
* address          = ADDRESS + ", " + CITY + " " + STATE  (Synthea splits street,
                    city, state into separate CSV columns; we re-join them for
                    the single free-text `address` field).
* phone            = Synthea's patients.csv has NO phone column. We derive a
                    deterministic phone per patient. All members of a household
                    (patients sharing an ADDRESS) are given the SAME phone so
                    Step 4's phone+address family-matching has real signal.
* email            = derived as first.last@example.medinsight.local (Synthea
                    doesn't export email addresses in the base CSV).
* blood_group      = Synthea has no blood type. Assigned pseudo-randomly from
                    Patient.BloodGroup choices as a reasonable synthetic default.
* allergies        = Synthea stores allergies in allergies.csv (a separate export),
                    not patients.csv. For simplicity we assign 0-2 realistic
                    allergies from a small curated pool as synthetic defaults.
* medical_history  = Synthea keeps diagnoses in conditions.csv. We synthesize a
                    short, age-appropriate medical-history note per patient so
                    the Medical History tab is populated. (Real condition imports
                    from conditions.csv are left for a future step.)

IMPORTANT
---------
ALL data produced here is synthetic, generated by / in the style of MITRE's
Synthea. It is NOT real patient data and must never be mistaken for PHI.
"""

